#!/usr/bin/env python3
"""Batch-verify the 36 never-attempted-by-sweep k_sst grid quads by
reusing each cell's OWN prior Feb2026 parameter set (per user
instruction, 2026-09-28) instead of donor-seeding. For each cell:
  1. ensure lte_run.sh exists (construct from the standard template if
     missing -- several of the prior 6 fixed cells had none)
  2. check backbone_ok on the existing lt.exe.p (independent of metric)
  3. TEST_ONLY-verify with DTW and with CC, record whichever wins
     (higher minimum score across the available triplet/pair, subject
     to passing the dLOD floor)
  4. write a JSON report -- does NOT touch the ledger or sync to
     Sep2026/ itself, so results can be reviewed before committing.

Cells whose backbone fails backbone_ok, or where neither metric clears
DLOD_FLOOR, are flagged "needs_donor_seed" for fallback to the existing
sweep.py flood-fill machinery.
"""
import json
import subprocess
import sys
import time
from pathlib import Path

sys.path.insert(0, "/home/paul/eval/gem-lte-core/experiments/Sep2026")
import sweep

CELLS = ['kN000_E010', 'kN000_E070', 'kN000_E130', 'kN000_E170', 'kN000_W010',
         'kN000_W050', 'kN000_W090', 'kN000_W110', 'kN000_W130', 'kN020_E130',
         'kN020_W010', 'kN020_W070', 'kN020_W090', 'kN020_W110', 'kN040_E010',
         'kN040_E030', 'kN040_E130', 'kN040_E170', 'kN040_W130', 'kN060_W130',
         'kN060_W150', 'kN080_E010', 'kS020_E090', 'kS020_E130', 'kS020_W010',
         'kS020_W030', 'kS020_W070', 'kS020_W150', 'kS020_W170', 'kS040_E010',
         'kS040_E030', 'kS040_E110', 'kS040_E130', 'kS040_W010', 'kS040_W030',
         'kS040_W070']

TEMPLATE = """#!/usr/bin/env bash
# Auto-generated by lte_gui.py's Run button -- reproduces that
# exact invocation. Run from this directory: ./lte_run.sh
cd "$(dirname "$0")"
export CLIMATE_INDEX={cell}.dat
export DLOD_REF=TRUE
export EXCLUDE=true
export F9=1
export IDATE=1920.9
export LOCKA=FALSE
export LOCKT=FALSE
export METRIC={metric}
export TEST_ONLY=true
export TIMEOUT=1000.000000
export TRAIN_END=2005
export TRAIN_START=2000
export TREND=true
export ZONE=FALSE
ulimit -s unlimited
../lt.exe -j
"""

REPORT_PATH = sweep.HERE / "verify_untouched_36_report.json"
LOG_PATH = sweep.HERE / "verify_untouched_36.log"


def log(msg: str) -> None:
    line = f"[{time.strftime('%Y-%m-%d %H:%M:%S')}] {msg}"
    print(line, flush=True)


def ensure_run_script(cell_dir: Path, cell: str, metric: str) -> Path:
    run_sh = cell_dir / "lte_run.sh"
    if run_sh.exists():
        text = run_sh.read_text()
        text = text.replace("export TEST_ONLY=false", "export TEST_ONLY=true")
        import re
        text = re.sub(r"export METRIC=\S+", f"export METRIC={metric}", text)
        if "export METRIC=" not in text:
            text = text.replace("export TEST_ONLY=true",
                                 f"export METRIC={metric}\nexport TEST_ONLY=true")
    else:
        text = TEMPLATE.format(cell=cell, metric=metric)
    run_sh.write_text(text)
    run_sh.chmod(0o755)
    return run_sh


CHECK_TIMEOUT_S = 20  # TEST_ONLY repeats the same result immediately and
                       # indefinitely (confirmed this session) -- unlike a
                       # real search attempt, it never needs the internal
                       # TIMEOUT+90s padding sweep.run_attempt uses, so a
                       # short external watch window is enough.


def verify_metric(cell: str, metric: str) -> dict:
    cell_dir = sweep.FEB / cell
    ensure_run_script(cell_dir, cell, metric)
    proc = subprocess.run(
        ["expect", "-f", str(sweep.WATCH_EXP), str(cell_dir), str(CHECK_TIMEOUT_S)],
        capture_output=True, text=True, timeout=CHECK_TIMEOUT_S + 30,
    )
    out = proc.stdout
    triplets, pairs, dlods = [], [], []
    deadlocked = False
    for line in out.splitlines():
        if line.startswith("MATCHED_TRIPLET:"):
            m = sweep.TRIPLET_RE.search(line)
            if m:
                triplets.append({"metric": m.group(1), "train": float(m.group(2)),
                                  "validate": float(m.group(3)), "test": float(m.group(4))})
        elif line.startswith("MATCHED_PAIR:"):
            m = sweep.PAIR_RE.search(line)
            if m:
                pairs.append({"val1": float(m.group(2)), "val2": float(m.group(3))})
        elif line.startswith("MATCHED_DEADLOCK:"):
            deadlocked = True
        elif line.startswith("MATCHED_DLOD:"):
            m = sweep.DLOD_RE.search(line)
            if m:
                dlods.append(float(m.group(1)))
    best_triplet = max(triplets, key=lambda t: t["train"]) if triplets else None
    best_pair = pairs[0] if pairs else None
    best_dlod = max(dlods) if dlods else None
    return dict(metric=metric, deadlocked=deadlocked,
                triplet=best_triplet, pair=best_pair, dlod=best_dlod)


def score_list(res: dict) -> list[float]:
    if res.get("triplet"):
        t = res["triplet"]
        return [t["train"], t["validate"], t["test"]]
    if res.get("pair"):
        return [res["pair"]["val1"], res["pair"]["val2"]]
    return []


def quality(res: dict) -> tuple[float, float]:
    """(min_score, mean_score) -- None-safe, unusable results sort last."""
    vals = score_list(res)
    if not vals or res.get("dlod") is None or res["dlod"] < sweep.DLOD_FLOOR:
        return (-999.0, -999.0)
    return (min(vals), sum(vals) / len(vals))


def main() -> None:
    report = {}
    for i, cell in enumerate(CELLS, 1):
        log(f"--- [{i}/{len(CELLS)}] {cell} ---")
        cell_dir = sweep.FEB / cell
        bb = sweep.read_backbone(cell_dir)
        bb_ok = sweep.backbone_ok(cell_dir)
        entry = dict(cell=cell, backbone=bb, backbone_ok=bb_ok)

        if not bb_ok:
            log(f"    backbone_ok=False (backbone={bb}) -- flagging needs_donor_seed, skipping metric checks")
            entry["needs_donor_seed"] = True
            report[cell] = entry
            with open(REPORT_PATH, "w") as f:
                json.dump(report, f, indent=2)
            continue

        try:
            dtw = verify_metric(cell, "DTW")
        except Exception as exc:
            dtw = dict(metric="DTW", error=str(exc))
        try:
            cc = verify_metric(cell, "CC")
        except Exception as exc:
            cc = dict(metric="CC", error=str(exc))

        entry["dtw"] = dtw
        entry["cc"] = cc
        q_dtw = quality(dtw) if "error" not in dtw else (-999.0, -999.0)
        q_cc = quality(cc) if "error" not in cc else (-999.0, -999.0)
        winner = "DTW" if q_dtw >= q_cc else "CC"
        entry["winner"] = winner
        entry["winner_quality"] = max(q_dtw, q_cc)
        entry["needs_donor_seed"] = max(q_dtw, q_cc)[0] <= -999.0

        log(f"    DTW quality={q_dtw}  CC quality={q_cc}  winner={winner}  "
            f"needs_donor_seed={entry['needs_donor_seed']}")

        report[cell] = entry
        with open(REPORT_PATH, "w") as f:
            json.dump(report, f, indent=2)

    n_ok = sum(1 for e in report.values() if not e.get("needs_donor_seed"))
    n_bad = sum(1 for e in report.values() if e.get("needs_donor_seed"))
    log(f"=== done: {n_ok} usable from prior work, {n_bad} need donor-seeding ===")
    (sweep.HERE / "VERIFY_36_DONE").write_text(
        f"{n_ok} usable, {n_bad} need donor-seed, {time.strftime('%Y-%m-%dT%H:%M:%S')}\n")


if __name__ == "__main__":
    main()
